# Specs for reading the size of RuboCop's offense backlog from .rubocop_todo.yml.

require_relative '../rubocop_todo'

describe CiSummary::RubocopTodo do

  describe '.counts' do
    it 'sums the offenses and counts the cops the backlog records' do
      todo = <<~YAML
        # This configuration was generated by
        # `rubocop --auto-gen-config --no-exclude-limit`

        # Offense count: 21
        # This cop supports safe autocorrection (--autocorrect).
        Lint/UnusedBlockArgument:
          Exclude:
            - 'Rakefile'

        # Offense count: 180
        # Configuration parameters: AllowedMethods, AllowedPatterns, CountRepeatedAttributes, Max.
        Metrics/AbcSize:
          Exclude:
            - 'lib/ceedling/configurator.rb'
      YAML

      expect(described_class.counts( todo )).to eq( 'offenses' => 201, 'cops' => 2 )
    end

    it 'reads an empty backlog as nothing outstanding' do
      expect(described_class.counts( "# No offenses\n" )).to eq( 'offenses' => 0, 'cops' => 0 )
    end
  end

end
